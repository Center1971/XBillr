#!/bin/bash
# Create admin user using the database directly

set -e

cd "$(dirname "$0")/.."

echo "Creating admin user..."

# Get database credentials from docker-compose
DB_ROOT_PASSWORD="${DB_ROOT_PASSWORD:-u9UUgy2ZwASrTebZ8pAGaCPnVSJZ8NRX}"
ADMIN_PASSWORD="${1:-admin123}"

# First, check if we can connect to the database
echo "Testing database connection..."
docker compose exec -T mariadb mysql -uroot -p"$DB_ROOT_PASSWORD" -e "SELECT 1;" > /dev/null 2>&1 || {
    echo "ERROR: Cannot connect to database. Check DB_ROOT_PASSWORD in docker-compose.yml"
    exit 1
}

# Create admin user via SQL (we'll need to hash the password properly)
# For now, let's use the Perl script but with explicit environment variables
echo "Creating admin user with password: $ADMIN_PASSWORD"
docker compose exec -T backend sh -c "
    export DB_DSN='dbi:MariaDB:database=xbillr;host=mariadb;port=3306'
    export DB_USER='root'
    export DB_PASSWORD='$DB_ROOT_PASSWORD'
    perl /app/scripts/create_admin.pl '$ADMIN_PASSWORD'
" || {
    echo ""
    echo "Alternative: Creating admin user directly via SQL..."
    echo "Note: Password hash will need to be generated by the application"
    echo ""
    echo "You can manually create the admin user by:"
    echo "1. Logging into the backend container: docker compose exec backend bash"
    echo "2. Running: perl /app/scripts/create_admin.pl admin123"
    echo ""
    echo "Or use the web interface after the first successful login."
}
